let current = "en";

// 언어 설정. 지원하지 않는 값이면 영어로.
export function setLang(lang) {
  current = DICT[lang] ? lang : "en";
}

export function getLang() {
  return current;
}

// 키로 문자열을 가져와 {name} 자리표시자를 params 로 치환한다.
export function t(key, params) {
  const s = (DICT[current] && DICT[current][key]) ?? DICT.en[key] ?? key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? params[k] : `{${k}}`));
}
