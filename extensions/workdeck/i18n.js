function detectLang() {
  let saved = null;
  try { saved = localStorage.getItem("workdeck.lang"); } catch { /* storage can be blocked */ }
  if (saved && LANGUAGES.some(([c]) => c === saved)) return saved;
  const sys = String((typeof navigator !== "undefined" && navigator.language) || "en").toLowerCase().split("-")[0];
  return LANGUAGES.some(([c]) => c === sys) ? sys : "en";
}
const LANG = detectLang();
const LOCALE = LANG === "ko" ? "ko-KR" : "en-US";
/* "auto" clears the override. The page that calls this should reload so already-built text is rebuilt. */
function setLang(code) {
  try { code === "auto" ? localStorage.removeItem("workdeck.lang") : localStorage.setItem("workdeck.lang", code); } catch { /* ignore */ }
}
function hasLangOverride() { try { return !!localStorage.getItem("workdeck.lang"); } catch { return false; } }

function tr(key, ...args) {
  let s = LANG === "ko" ? key : (I18N[LANG] && I18N[LANG][key]);
  if (s === undefined) s = key;
  return args.length ? s.replace(/\{(\d+)\}/g, (m, i) => (i < args.length ? String(args[i]) : m)) : s;
}

/* Static text in the page's HTML (text nodes, title, placeholder, aria-label) is translated once the DOM exists. */
function translateDom(root) {
  if (LANG === "ko") return;
  const table = I18N[LANG] || {};
  const swap = (raw) => { const k = raw.trim(); return k && table[k] !== undefined ? raw.replace(k, table[k]) : raw; };
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) if (/[가-힣]/.test(n.nodeValue)) n.nodeValue = swap(n.nodeValue);
  root.querySelectorAll("[title],[placeholder],[aria-label]").forEach((e) => {
    for (const a of ["title", "placeholder", "aria-label"]) if (e.hasAttribute(a)) e.setAttribute(a, swap(e.getAttribute(a)));
  });
  document.title = swap(document.title);
}
if (typeof document !== "undefined") {
  document.documentElement.lang = LANG;
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", () => translateDom(document.documentElement));
  else translateDom(document.documentElement);
}

/* DOM safety (loaded first on every page): append / prepend / replaceChildren turn a null or false argument into the
 * text "null" / "false". Conditional children like `cond ? el(...) : null` are skipped instead. */
if (typeof Element !== "undefined") {
  for (const m of ["append", "prepend", "replaceChildren"]) {
    const original = Element.prototype[m];
    Element.prototype[m] = function (...nodes) { return original.apply(this, nodes.filter((n) => n != null && n !== false)); };
  }
}
